-- --------------------------------------------------------------- projects ----
create table if not exists public.projects (
  id            bigint generated by default as identity primary key,
  title         text not null,
  slug          text,
  subtitle      text,
  description   text,
  category      text default 'PERSONAL',
  tags          jsonb,                -- string[]
  image_url     text,
  live_url      text,
  github_url    text,
  metrics       jsonb,                -- { [key]: string }
  featured      boolean default false,
  display_order int default 0,
  created_at    timestamptz default now()
);

alter table public.projects enable row level security;

-- ---------------------------------------------------------------- thoughts ----
create table if not exists public.thoughts (
  id            bigint generated by default as identity primary key,
  title         text not null,
  slug          text,
  summary       text,
  content       text,
  tags          jsonb,                -- string[]
  read_time     text default '3 MIN READ',
  likes_count   int default 0,
  published_at  timestamptz default now(),
  featured      boolean default false
);

alter table public.thoughts enable row level security;

-- ------------------------------------------------------------------ skills ----
create table if not exists public.skills (
  id            bigint generated by default as identity primary key,
  name          text not null,
  category      text default 'LANGUAGES & TOOLS',
  level         int default 85,
  icon          text,
  display_order int default 0
);

alter table public.skills enable row level security;

-- --------------------------------------------------------------- guestbook ----
create table if not exists public.guestbook (
  id           bigint generated by default as identity primary key,
  name         text not null,
  handle       text default '@guest',
  message      text not null,
  avatar_color text default 'cyan',
  badge        text default 'VISITOR',
  approved     boolean default false,   -- entries need admin approval
  created_at   timestamptz default now()
);

alter table public.guestbook enable row level security;

-- --------------------------------------------------------------- messages ----
create table if not exists public.messages (
  id           bigint generated by default as identity primary key,
  sender_name  text not null,
  sender_email text not null,
  subject      text,
  body         text,
  read_status  boolean default false,
  created_at   timestamptz default now()
);

alter table public.messages enable row level security;

