-- ---------------------------------------------------------------- profile ----
create table if not exists public.profile (
  id                 bigint generated by default as identity primary key,
  full_name          text default 'Baba Muteeb',
  title              text,
  bio                text,
  status_badge       text,
  location           text,
  available_for_work boolean default true,
  accent_color       text,
  email              text default 'hello@muteeb.in',
  instagram_handle   text default '@mr_muteeb_',
  headline           text,
  logo_url           text default '/images/logo.png',
  sound_enabled      boolean default true,
  typewriter_roles   jsonb,  -- string[]
  now_focus          jsonb,  -- { title, desc }[]
  quick_facts        jsonb,  -- string[]
  admin_passcode     text,
  github_url         text,
  twitter_url        text,
  linkedin_url       text,
  created_at         timestamptz default now(),
  updated_at         timestamptz default now()
);

alter table public.profile enable row level security;

